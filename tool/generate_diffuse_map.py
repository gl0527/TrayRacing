#!/usr/bin/env python3
"""Convert an RGB image into a generated C diffuse-map header.

Requires Pillow: python3 -m pip install Pillow
"""

import argparse
import math
import re
from pathlib import Path

from PIL import Image


def identifier(name: str) -> str:
    value = re.sub(r"\W", "_", name)
    if not value or value[0].isdigit():
        value = "_" + value
    return value


def linearize(channel: int) -> float:
    value = channel / 255.0
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def generate(source: Path, destination: Path) -> None:
    stem = identifier(source.stem)
    type_name = f"DiffuseMap{stem}"
    array_name = f"diffuseMap{stem}Data"
    instance_name = f"diffuseMap{stem}"

    with Image.open(source) as image:
        image = image.convert("RGB")
        width, height = image.size
        pixels = list(image.getdata())

    lines = [
        "/* Generated by tool/generate_diffuse_map.py; do not edit. */",
        "#ifndef TRAYRACING_H",
        '#error "Include trayracing/trayracing.h before this generated map"',
        "#endif",
        "",
        f"typedef struct {type_name} {{",
        "    uint32_t width;",
        "    uint32_t height;",
        "    Vec3 const *data;",
        f"}} {type_name};",
        "",
        f"static const Vec3 {array_name}[{width * height}] = {{",
    ]
    for r, g, b in pixels:
        lines.append(
            f"    {{{linearize(r):.9g}f, {linearize(g):.9g}f, {linearize(b):.9g}f}},"
        )
    lines.extend([
        "};",
        f"static const {type_name} {instance_name} = {{",
        f"    {width}u, {height}u, {array_name}",
        "};",
        "",
    ])
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="source image file")
    parser.add_argument("output", type=Path, help="generated C header path")
    args = parser.parse_args()
    generate(args.image, args.output)


if __name__ == "__main__":
    main()
